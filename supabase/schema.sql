  user_id bigint primary key references users(id) on delete cascade,
  notifications jsonb not null default '{"messages":true,"sounds":true,"previews":true}'::jsonb,
  data_usage jsonb not null default '{"autoplay":true,"autoDownloadImages":true,"autoDownloadVideos":false,"autoDownloadAudio":false}'::jsonb,
  privacy jsonb not null default '{"lastSeen":"everyone","profilePhoto":"everyone","readReceipts":true}'::jsonb,
  security jsonb not null default '{"twoStep":false}'::jsonb,
  updated_at timestamptz not null default now()
);
