alter table conversation_members add column if not exists role text not null default 'member';
alter table conversations add column if not exists photo text not null default '';
create table if not exists conversation_admins (
  conversation_id bigint not null references conversations(id) on delete cascade,
  user_id bigint not null references users(id) on delete cascade,
  role text not null default 'admin' check (role in ('owner','admin','moderator')),
  permissions jsonb not null default '{"post":true,"edit":true,"delete":true,"invite":true,"ban":false,"manage":false}'::jsonb,
  created_at timestamptz not null default now(),
  primary key(conversation_id,user_id)
);
